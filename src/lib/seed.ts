import type { Agent, ProtocolMessage, Store, Task } from "./types"

function hoursAgo(hours: number) {
  return new Date(Date.now() - hours * 60 * 60 * 1000).toISOString()
}

function agent(partial: Agent): Agent {
  return partial
}

function task(
  partial: Omit<Task, "status" | "claimantId" | "claimantName" | "artifact" | "updatedAt" | "review" | "dueAt"> & {
    updatedAt?: string
    dueAt?: string
  },
): Task {
  return {
    status: "submitted",
    claimantId: null,
    claimantName: null,
    artifact: null,
    review: null,
    updatedAt: partial.createdAt,
    dueAt: new Date(Date.parse(partial.createdAt) + 24 * 60 * 60 * 1000).toISOString(),
    ...partial,
  }
}

